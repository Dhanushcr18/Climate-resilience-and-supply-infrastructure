export const EDGE_MAP = new Map<string, NetworkEdge>(
  EDGES.map((edge) => [edge.id, edge])
);

/**
 * Helper to get edge between two node IDs (undirected)
 */
export function getEdgeBetween(
  fromNode: string,
  toNode: string
): NetworkEdge | undefined {
  return EDGES.find(
    (e) =>
      (e.from === fromNode && e.to === toNode) ||
      (e.from === toNode && e.to === fromNode)
  );
}

/**
 * Returns the midpoint [lat, lng] of an edge's polyline
 */
export function getEdgeMidpoint(edge: NetworkEdge): PointTuple {
  const pts = edge.path;
  if (pts.length === 0) return [0, 0];
  const midIdx = Math.floor(pts.length / 2);
  return pts[midIdx];
}

/**
 * Helper to get the region of a node
 */
export function getNodeRegion(nodeId: string): RegionId {
  return NODES[nodeId]?.region || "south";
}
